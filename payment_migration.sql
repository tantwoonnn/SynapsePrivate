-- Payment records and learner completion confirmation for PayMongo Checkout.
-- Safe to run more than once on PostgreSQL/Supabase.
ALTER TABLE appointments ADD COLUMN IF NOT EXISTS completion_confirmed_at TIMESTAMPTZ;
ALTER TABLE appointments ADD COLUMN IF NOT EXISTS completion_issue VARCHAR(500);

CREATE TABLE IF NOT EXISTS appointment_payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    appointment_id BIGINT NOT NULL UNIQUE REFERENCES appointments(id) ON DELETE CASCADE,
    reference_number VARCHAR(80) NOT NULL UNIQUE,
    checkout_session_id VARCHAR(100) UNIQUE,
    checkout_url TEXT,
    amount_minor INTEGER NOT NULL CHECK (amount_minor > 0),
    currency CHAR(3) NOT NULL DEFAULT 'PHP',
    payment_method VARCHAR(10) NOT NULL DEFAULT 'PAYMONGO',
    status VARCHAR(10) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'PAID')),
    provider_payment_id VARCHAR(100),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    paid_at TIMESTAMPTZ
);

ALTER TABLE appointment_payments ADD COLUMN IF NOT EXISTS payment_method VARCHAR(10) NOT NULL DEFAULT 'PAYMONGO';
DO $$ BEGIN
