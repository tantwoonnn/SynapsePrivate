-- PostgreSQL schema for a new Synapse Supabase project.
-- Run in Supabase SQL Editor only after the PHP application is converted to PostgreSQL.

CREATE TABLE IF NOT EXISTS app_sessions (
    id VARCHAR(128) PRIMARY KEY,
    payload TEXT NOT NULL,
    last_activity BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_app_sessions_last_activity ON app_sessions(last_activity);

CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(100) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(10) NOT NULL DEFAULT 'user' CHECK (role IN ('admin', 'staff', 'user')),
    is_verified SMALLINT NOT NULL DEFAULT 1 CHECK (is_verified IN (0, 1)),
    verification_token CHAR(32) UNIQUE,
    token_expires_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS tutor_applications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    learner_id BIGINT NOT NULL UNIQUE REFERENCES users(id) ON DELETE CASCADE,
    academic_program VARCHAR(120) NOT NULL,
    subjects VARCHAR(300) NOT NULL,
    experience TEXT NOT NULL,
    motivation TEXT NOT NULL,
    attachment_path VARCHAR(80),
    attachment_name VARCHAR(255),
    status VARCHAR(10) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED')),
    admin_note VARCHAR(500),
    applied_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    reviewed_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
    reviewed_at TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS idx_tutor_application_status ON tutor_applications(status, applied_at);

CREATE TABLE IF NOT EXISTS courses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_code VARCHAR(20) NOT NULL UNIQUE,
    course_name VARCHAR(150) NOT NULL,
    department VARCHAR(100) NOT NULL
);

CREATE TABLE IF NOT EXISTS tutor_schedules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tutor_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    day_of_week SMALLINT NOT NULL CHECK (day_of_week BETWEEN 0 AND 6),
    start_time TIME NOT NULL,
    end_time TIME NOT NULL CHECK (end_time > start_time),
    is_available SMALLINT NOT NULL DEFAULT 1 CHECK (is_available IN (0, 1)),
    UNIQUE (tutor_id, day_of_week, start_time, end_time)
);

CREATE TABLE IF NOT EXISTS tutor_courses (
    tutor_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    course_id BIGINT NOT NULL REFERENCES courses(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (tutor_id, course_id)
);
CREATE INDEX IF NOT EXISTS idx_tutor_course_course ON tutor_courses(course_id);

CREATE TABLE IF NOT EXISTS appointments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    learner_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    tutor_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    course_id BIGINT NOT NULL REFERENCES courses(id) ON DELETE RESTRICT,
    booking_date DATE NOT NULL,
    session_time TIME NOT NULL,
    end_time TIME NOT NULL CHECK (end_time > session_time),
    contact_info VARCHAR(150),
    status VARCHAR(10) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'CONFIRMED', 'COMPLETED', 'CANCELLED')),
    notes VARCHAR(500),
    rejection_reason VARCHAR(500),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_appointment_tutor_slot ON appointments(tutor_id, booking_date, session_time, status);
CREATE INDEX IF NOT EXISTS idx_appointment_learner ON appointments(learner_id);
CREATE INDEX IF NOT EXISTS idx_appointment_queue ON appointments(status, created_at);

CREATE TABLE IF NOT EXISTS session_reviews (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    appointment_id BIGINT NOT NULL UNIQUE REFERENCES appointments(id) ON DELETE CASCADE,
    rating SMALLINT NOT NULL CHECK (rating BETWEEN 1 AND 5),
    comment VARCHAR(500),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS activity_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    action VARCHAR(50) NOT NULL,
    details VARCHAR(500),
    log_timestamp TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_log_time ON activity_logs(log_timestamp);

